const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

/**
 * Render text as pixel squares. Returns an HTML string: an aria-hidden SVG plus
 * a visually hidden copy of the text for screen readers, search and copy.
 * `accent` maps character indexes to a CSS class (used for the orange full stop).
 */
export function pixelText(text, { gap = 0.86, cls = '', accentLast = false } = {}) {
  const chars = [...String(text).toUpperCase()];
  let x = 0;
  const main = [];
  const accent = [];
  chars.forEach((ch, i) => {
    const g = G[ch] ?? G['?'];
    const w = g[0].length;
    const target = accentLast && i === chars.length - 1 ? accent : main;
    g.forEach((row, y) => {
      for (let c = 0; c < w; c++) if (row[c] === '#') target.push(`M${x + c} ${y}h${gap}v${gap}h-${gap}z`);
    });
    x += w + 1;
  });
  const width = Math.max(x - 1, 1);
  const svg =
    `<svg class="px-svg" viewBox="0 0 ${width} 7" width="${width}" height="7" aria-hidden="true" focusable="false" shape-rendering="crispEdges">` +
    `<path d="${main.join('')}" fill="currentColor"/>` +
    (accent.length ? `<path class="px-accent" d="${accent.join('')}"/>` : '') +
    `</svg>`;
  return `<span class="px ${cls}">${svg}<span class="sr">${esc(text)}</span></span>`;
}

