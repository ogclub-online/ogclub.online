const KEY = { g: 'var(--px-g)', w: 'var(--px-w)', s: 'var(--px-s)', j: 'var(--px-j)', k: 'var(--px-k)', d: 'var(--px-d)' };

export function crownSvg(label = 'OG Club pass emblem') {
  const byColor = {};
  CROWN.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      if (ch === '.') return;
      (byColor[ch] ??= []).push(`M${x} ${y}h1v1h-1z`);
    });
  });
  const paths = Object.entries(byColor).map(([k, d]) => `<path d="${d.join('')}" fill="${KEY[k]}"/>`).join('');
  return `<svg class="emblem" viewBox="0 0 24 24" role="img" aria-label="${esc(label)}" shape-rendering="crispEdges"><rect width="24" height="24" fill="var(--px-bg)"/>${paths}</svg>`;
}
